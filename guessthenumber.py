import random

number = random.randint(1, 100)
lives = int(input("How many attempts you want? ")) #You can decide how many lives you've got!
for attempt in range(lives, 0, -1):
  print("You only have", attempt, "lives left!")
  guess = int(input("What's the number? "))
  if guess > number:
    print("Too high!")
  elif guess < number:
    print("Too low!")
  else:
    print("You won!")